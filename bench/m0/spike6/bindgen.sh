#!/usr/bin/env bash
# Regenerates tools/acoustic-bake/src/phonon_sys.rs from the Steam Audio SDK header.
# Userland only: bindgen-cli from cargo, libclang from the PyPI `libclang` wheel in a uv venv
# (the system has libclang-cpp but not libclang.so).
set -euo pipefail

SDK=/home/akram/code/or3/data/raw/steam-audio/sdk/steamaudio
VENV=/home/akram/code/or3/data/raw/libclang-venv
REPO="$(cd "$(dirname "$0")/../../.." && pwd)"

[ -x "$HOME/.cargo/bin/bindgen" ] || cargo install bindgen-cli --version 0.73.2 --locked -j3
if [ ! -d "$VENV/.venv" ]; then
  mkdir -p "$VENV" && uv venv -q "$VENV/.venv"
  uv pip install -q --python "$VENV/.venv/bin/python" libclang==18.1.1
fi
LIBCLANG_PATH="$(dirname "$(find "$VENV/.venv" -name 'libclang.so' | head -1)")"
export LIBCLANG_PATH

"$HOME/.cargo/bin/bindgen" "$SDK/include/phonon.h" \
  --allowlist-function 'ipl.*' --allowlist-type 'IPL.*' --allowlist-var 'IPL.*|STEAMAUDIO.*' \
  --no-layout-tests --no-doc-comments --default-enum-style rust --bitfield-enum 'IPL.*Flags' \
  --raw-line '// Generated by bindgen 0.73.2 from Steam Audio 4.8.1 include/phonon.h (Apache-2.0, Valve Corporation).' \
  --raw-line '// Regenerate: see bench/m0/spike6/bindgen.sh' \
  --raw-line '#![allow(non_camel_case_types, non_snake_case, non_upper_case_globals, dead_code, clippy::all)]' \
  -o "$REPO/tools/acoustic-bake/src/phonon_sys.rs" -- -I"$SDK/include"
# match the committed formatting
cargo fmt -p acoustic-bake --manifest-path "$REPO/Cargo.toml"
